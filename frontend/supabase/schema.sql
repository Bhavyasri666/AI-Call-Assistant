
-- AI Call Assistant: Supabase database schema
-- This file documents the calls table structure.

CREATE TABLE IF NOT EXISTS public.calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transcript_id TEXT UNIQUE NOT NULL,
    transcript TEXT NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    stage TEXT NOT NULL DEFAULT 'Opening',
    stage_event TEXT NOT NULL DEFAULT '',
    prospect_words TEXT NOT NULL DEFAULT '',
    outcome TEXT NOT NULL DEFAULT 'Other',
    next_step TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT calls_stage_check CHECK (
        stage IN (
            'Opening',
            'Purpose',
            'Permission',
            'Their Business',
            'Their Need',
            'Objection',
            'Next Step',
            'Close'
        )
    ),

    CONSTRAINT calls_outcome_check CHECK (
        outcome IN (
            'Interested',
            'Callback Requested',
            'Not Interested',
            'No Answer',
            'Wrong Person',
            'Call Ended',
            'Other'
        )
    )
);

CREATE INDEX IF NOT EXISTS idx_calls_created_at
ON public.calls (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_calls_stage
ON public.calls (stage);
